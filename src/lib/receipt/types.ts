// Типы результата распознавания чека.
// Суммы здесь — в валюте самого чека, в «крупных» единицах (напр. 58900 для IDR,
// 420.50 для RUB). Перевод в минорные единицы валюты поездки — это уже забота
// money.ts при создании траты, распознавание про поездку ничего не знает.

/** Тип чека. Правило 9 из контекста. */
export type ReceiptKind =
  | 'itemized' // есть позиции по людям: ресторан, доставка еды — делим по людям
  | 'single'; // одна услуга: такси, перевод — делим целиком между участниками

/** Причина, по которой приложение просит человека проверить/дополнить распознанное. */
export type ReviewReason =
  | 'total_not_found' // итог (Total Paid) на фото не виден
  | 'sum_mismatch' // сумма позиций (+сбор/чай) не сошлась с итогом — правило 1
  | 'currency_guessed' // валюту угадали по стране/адресу — правило 6, нужно подтвердить
  | 'date_not_found' // дату с чека не нашли — правило 8, нужна для курса
  | 'no_items_found' // тип itemized, но позиций не распознано
  | 'partial_receipt'; // чек обрезан/закрыт — возможно, не все позиции (нужно доснять, правило 2)

export interface ReceiptItem {
  /** Название позиции. Модификаторы/состав сета приклеены сюда (правило 3). */
  name: string;
  /**
   * Сумма по строке целиком, как напечатано на чеке (не цена за единицу).
   * Для «2 стейка 1800» это 1800, а quantity = 2.
   */
  amount: number;
  /** Количество. Для деления поштучно (правило 4). Минимум 1. */
  quantity: number;
  /** Сырая строка суммы с чека — для отладки и перепроверки формата чисел. */
  rawAmount?: string;
  /** Если чек уже разбит по гостям (правило 7) — ярлык гостя, напр. "Гость 2". */
  guestLabel?: string;
  /**
   * Кто ест/владеет позицией. На этапе распознавания обычно пусто —
   * заполняется людьми на экране. Задел под мультиюзер (ownerIds в данных).
   */
  ownerIds: string[];
}

/** То, что возвращает модель (до нашей детерминированной сверки). */
export interface ModelReceipt {
  kind: ReceiptKind;
  /** ISO-код валюты, если понятно с чека (RUB, IDR, USD, USDT…), иначе null. */
  currency: string | null;
  /** true, если валюту пришлось угадать по стране/адресу (правило 6). */
  currencyGuessed: boolean;
  /** Дата с чека в формате YYYY-MM-DD, иначе null (правило 8). */
  date: string | null;
  /** Позиции. Пусто для kind='single'. */
  items: ReceiptItem[];
  /**
   * Итог чека — только «Total Paid» / «Итого к оплате».
   * НЕ скидка, НЕ сдача, НЕ внесённые наличные, НЕ строка НДС/VAT (правило 5).
   * null, если итога на фото не видно.
   */
  total: number | null;
  /** Сервисный сбор отдельной строкой, если есть (делится поровну). Иначе 0. */
  serviceCharge: number;
  /** Чаевые отдельной строкой, если есть (делятся поровну). Иначе 0. */
  tip: number;
  /** true, если чек уже разбит по гостям (правило 7). */
  guestSplitDetected: boolean;
  /** true, если чек визуально обрезан/перекрыт — возможно, не все позиции. */
  looksPartial: boolean;
  /** Свободная заметка модели о странностях (язык, скидка и т.п.), иначе null. */
  note: string | null;
}

/** Итог распознавания: ответ модели + результат нашей детерминированной сверки. */
export interface RecognizedReceipt extends ModelReceipt {
  /** Сумма позиций (Σ amount по строкам). null, если позиций нет. */
  itemsSum: number | null;
  /**
   * Сошлась ли сумма с итогом:
   *  true  — сошлась,
   *  false — не сошлась,
   *  null  — проверить нельзя (нет итога или нет позиций).
   */
  totalMatches: boolean | null;
  /** total − (Σ позиций + сбор + чай). null, если проверить нельзя. */
  difference: number | null;
  /** Нужно ли показать человеку «проверь, пожалуйста». */
  needsReview: boolean;
  /** Конкретные причины для needsReview. */
  reviewReasons: ReviewReason[];
}
